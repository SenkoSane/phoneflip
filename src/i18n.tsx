const dicts: Record<Lang, Record<string, string>> = { nl, en }

function readLang(): Lang {
  try {
    const raw = localStorage.getItem(LANG_KEY)
    if (raw === 'en' || raw === 'nl') return raw
  } catch {
    /* ignore */
  }
  return 'nl'
}

let currentLang: Lang = readLang()

export function getLang(): Lang {
  return currentLang
}

export function localeFor(lang: Lang = currentLang): string {
  return lang === 'en' ? 'en-GB' : 'nl-NL'
}

export function dateLocale(lang: Lang = currentLang): string {
  return localeFor(lang)
}

export function tr(key: string, vars?: Record<string, string | number>, lang: Lang = currentLang): string {
  let s = dicts[lang][key] ?? dicts.nl[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  }
  return s
}

